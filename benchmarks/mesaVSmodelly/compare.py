"""Run the same notebook on Mesa 2.3 and on Modelly, then compare everything.

Each framework runs in its own venv (Mesa 2.3 and Modelly cannot share one):

- Mesa    -> ``.venv-mesa2/bin/python``
- Modelly -> ``.venv/bin/python``

Both execute the *entire* notebook (every cell: simulations, CSVs, figures) in
a clean directory, so the work is identical. The two notebooks are the same
study; the Modelly one is the port generated by ``port_to_modelly.py``.

Output: a ``comparison.md`` report plus ``results/mesa.json`` and
``results/modelly.json``.

Usage:
    python benchmarks/mesaVSmodelly/compare.py
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent

MESA_NB = HERE / "mesa" / "Notebook_ABM_TIS_Optimise.ipynb"
MODELLY_NB = HERE / "modelly" / "Notebook_ABM_TIS_Optimise_Modelly.ipynb"
RESULTS = HERE / "results"

JOBS = [
    ("mesa", REPO / ".venv-mesa2" / "bin" / "python", MESA_NB, "step"),
    ("modelly", REPO / ".venv" / "bin" / "python", MODELLY_NB, "advance_day"),
]


def run(framework: str, python: Path, notebook: Path) -> None:
    print(f"\n=== running {framework} ({python}) ===", flush=True)
    cmd = [str(python), str(HERE / "runner.py"), str(notebook), framework, str(RESULTS)]
    proc = subprocess.run(cmd, cwd=notebook.parent, text=True)
    if proc.returncode != 0:
        raise SystemExit(f"{framework} run failed (exit {proc.returncode})")


def load(framework: str) -> dict:
    return json.loads((RESULTS / f"{framework}.json").read_text(encoding="utf-8"))


def main() -> None:
    for framework, python, notebook, _step_fn in JOBS:
        if not python.exists():
            raise SystemExit(f"missing venv: {python}")
        run(framework, python, notebook)

    mesa = load("mesa")
    modelly = load("modelly")

    # ---- wall-clock -----------------------------------------------------
    t_m, t_mo = mesa["total_seconds"], modelly["total_seconds"]
    speedup = t_m / t_mo if t_mo else float("inf")

    lines: list[str] = []
    add = lines.append
    add("# Mesa vs Modelly — same notebook, same seeds")
    add("")
    add(f"- Mesa {mesa['version']}   (`.venv-mesa2`): **{t_m:.2f} s**")
    add(f"- Modelly {modelly['version']} (`.venv`):       **{t_mo:.2f} s**")
    add(
        f"- Speedup: **{speedup:.2f}×** {'(Modelly faster)' if t_mo < t_m else '(Modelly slower)'}"
    )
    add("")
    add("## Per-cell wall-clock (seconds)")
    add("")
    add("| cell | Mesa | Modelly | Δ (M−Mo) |")
    add("| --- | --- | --- | --- |")
    mesa_cells = {c["cell"]: c["seconds"] for c in mesa["per_cell"]}
    modelly_cells = {c["cell"]: c["seconds"] for c in modelly["per_cell"]}
    for i in sorted(mesa_cells):
        a, b = mesa_cells[i], modelly_cells.get(i, 0.0)
        add(f"| {i} | {a:.2f} | {b:.2f} | {a - b:+.2f} |")
    add("")

    # ---- results equivalence -------------------------------------------
    add("## Results equivalence (the CSVs the notebook produces)")
    add("")
    mesa_out = mesa["outputs"]
    modelly_out = modelly["outputs"]
    all_names = sorted(set(mesa_out) | set(modelly_out))
    identical = True
    for name in all_names:
        if name not in mesa_out or name not in modelly_out:
            add(f"- **{name}**: missing on one side ❌")
            identical = False
            continue
        a, b = mesa_out[name], modelly_out[name]
        same = a["sha256"] == b["sha256"]
        identical &= same
        rows_a, rows_b = a["rows"], b["rows"]
        add(
            f"- **{name}**: {'IDENTICAL ✓' if same else 'DIFFERS ✗'} "
            f"(rows {rows_a} vs {rows_b}, sha256 {a['sha256'][:12]}… vs {b['sha256'][:12]}…)"
        )
    add("")
    add(
        "**Verdict:** the two frameworks produce "
        + ("bit-identical outputs" if identical else "DIFFERENT outputs — investigate")
        + "."
    )

    (HERE / "comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {HERE / 'comparison.md'}")


if __name__ == "__main__":
    main()
