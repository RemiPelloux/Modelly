"""Execute the benchmark notebooks headlessly and record their timings.

    python benchmarks/notebooks/run_notebooks.py            # all notebooks
    python benchmarks/notebooks/run_notebooks.py flocking   # those whose name contains the text

Writes ``results/<name>.json`` (the RESULT rows and the wall time) and
``results/README.md`` (one table per notebook). The executed notebooks are
written back with their outputs so they read well on GitHub.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

import nbformat
from nbclient import NotebookClient

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
TIMEOUT_SECONDS = 1800
RESULT_PREFIX = "RESULT "


def execute(path: Path) -> tuple[nbformat.NotebookNode, float]:
    """Run one notebook in place and return it with its wall time in seconds."""
    nb = nbformat.read(path, as_version=4)
    client = NotebookClient(
        nb,
        timeout=TIMEOUT_SECONDS,
        kernel_name="python3",
        resources={"metadata": {"path": str(HERE)}},
    )
    start = time.perf_counter()
    client.execute()
    return nb, time.perf_counter() - start


def result_rows(nb: nbformat.NotebookNode) -> list[dict]:
    """Collect the RESULT lines printed by the notebook's cells."""
    rows = []
    for cell in nb.cells:
        for output in cell.get("outputs", []):
            for line in output.get("text", "").splitlines():
                if line.startswith(RESULT_PREFIX):
                    rows.append(json.loads(line[len(RESULT_PREFIX) :]))
    return rows


def render_table(name: str, wall: float, rows: list[dict]) -> str:
    """One markdown table for a notebook's rows."""
    out = [
        f"## {name} ({wall:.1f} s)",
        "",
        "| workload | agents | ms / step | µs / agent-step |",  # noqa: RUF001 (micro sign)
        "|---|---|---|---|",
    ]
    out += [
        f"| {r['label']} | {r['agents']:,} | {r['ms_per_step']} | {r['us_per_agent_step']} |"
        for r in rows
    ]
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    """Run the selected notebooks and write the results."""
    RESULTS.mkdir(exist_ok=True)
    selected = [
        p
        for p in sorted(HERE.glob("*.ipynb"))
        if not argv or any(a in p.stem for a in argv)
    ]
    sections = []
    for path in selected:
        nb, wall = execute(path)
        nbformat.write(nb, path)
        rows = result_rows(nb)
        (RESULTS / f"{path.stem}.json").write_text(
            json.dumps({"wall_seconds": wall, "rows": rows}, indent=2), encoding="utf-8"
        )
        sections.append(render_table(path.stem, wall, rows))
        sys.stdout.write(f"{path.stem}: {wall:.1f} s, {len(rows)} rows\n")
    header = "# Benchmark notebooks\n\nGenerated by run_notebooks.py; wall-clock, single run, this machine.\n\n"
    (RESULTS / "README.md").write_text(header + "\n".join(sections), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
